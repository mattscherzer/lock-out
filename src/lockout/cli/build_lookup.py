"""Empirical Bayes model v0: score both backtest folds, write the lookup file and docs/eb-model-results.md (issue #38, roadmap M4).

Run from the repo root: uv run python -m lockout.cli.build_lookup [path to the police CSV]
Scores the model on both backtest folds against the targets, writes docs/eb-model-results.md,
and writes data/processed/lookup_schema_v1.json for all 542 areas, checked against schemas/lookup_v1.schema.json.
Each area carries its tier, confidence and statistics, and the metadata the citywide facts (issue #63).
"""
import sys

from lockout.cli.common import load_cleaned, require_folds_complete
from lockout.lookup.generate import generate, write_lookup
from lockout.models.area_stats import LIMITED_DATA_BELOW
from lockout.models.evaluate import evaluate, selector_flags, targets
from lockout.models.selectors import BIKE_VALUE_SPLIT_EUR
from lockout.paths import DOCS_DIR, LOOKUP

RESULTS = DOCS_DIR / "eb-model-results.md"


def markdown(rows, checks, lookup, reports_up_to, cutoff, source):
    lines = [f"| {f} | {t} | {v} | {'pass' if ok else 'MISS'} |" for f, t, v, ok in checks]
    folds = [f"| {r['fold']} | {r['deviance']:.3f} | {r['citywide']:.3f} | {r['raw']:.3f} | {r['spearman']:.3f} | {r['high_in_top_quartile']:.0%} | {r['raw_high_in_top_quartile']:.0%} |" for r in rows]
    flagged = sum(a["no_record"] for a in lookup["areas"].values())
    limited = sum(a["limited_data"] for a in lookup["areas"].values())
    confidence = {c: sum(a["confidence"] == c for a in lookup["areas"].values()) for c in ("LOW", "MEDIUM", "HIGH")}
    own = sum(a["area_stats"]["median_source"] == "area" for a in lookup["areas"].values())
    facts = lookup["metadata"]["citywide_facts"]
    return f"""# EB Model v0 Results

Generated by `uv run python -m lockout.cli.build_lookup data/raw/{source}` from `{source}` (not in Git), with reports up to {reports_up_to:%d %b %Y} and thefts counted up to the 14-day cutoff, {cutoff:%d %b %Y}. The committed `data/processed/lookup_schema_v1.json` comes from the same run. The baselines and folds are the ones in `docs/backtest-results.md`; compare models on the same file.

## Model

- Gamma-Poisson Empirical Bayes: each area's count is pulled toward its Bezirksregion, and each Bezirksregion toward the city. The prior strengths are estimated from the data (method of moments). An area with few thefts is pulled more strongly.
- Tiers are relative percentile bands of areas: Low 60%, Medium 25%, High 15%. Areas with the same rate get the same tier, the higher one.
- v0 scope: time band, day group and bike value (one split at EUR {BIKE_VALUE_SPLIT_EUR}) are stored as citywide shares under `selectors` in the lookup file (D-18), each with its flag from the hold-out validation; the checks are in `docs/validation-report.md`. No area carries multiplied values, and as citywide multipliers they never change an area's tier.

## Targets (G1)

The Spearman target is checked on the last fold only, as the issue states.

| Fold | Target | Value | Result |
| --- | --- | --- | --- |
{chr(10).join(lines)}

## Per fold

"High in top quartile" is shown for the raw area history too: on its own it does not show whether the model beats the baseline. Areas with 0 actual thefts never count as top quartile.

| Fold | EB deviance | Citywide share | Raw area history | Spearman | High in top quartile (EB) | High in top quartile (raw history) |
| --- | --- | --- | --- | --- | --- | --- |
{chr(10).join(folds)}

## Generator output

`data/processed/lookup_schema_v1.json` (schema {lookup['metadata']['schema_version']}, checked against `schemas/lookup_v1.schema.json`): {len(lookup['areas'])} areas, data window {lookup['metadata']['data_window']['start']} to {lookup['metadata']['data_window']['end']}. {flagged} areas have no street theft at all in the cleaned data (`no_record`), {limited} have fewer than {LIMITED_DATA_BELOW} street thefts in the window (`limited_data`).

- **Confidence** (`src/lockout/models/area_stats.py`, issue #57): LOW {confidence['LOW']}, MEDIUM {confidence['MEDIUM']}, HIGH {confidence['HIGH']} areas. LOW is the same line as `limited_data`.
- **Median stolen value:** {own} areas have their own median; the other {len(lookup['areas']) - own} show the citywide one.
- **Citywide facts:** median stolen value EUR {facts['median_stolen_value_eur']:,}, lock-defeated share {facts['lock_defeated_share']:.0%}.
"""


def main():
    path, cleaned, areas, reports_up_to, cutoff = load_cleaned(sys.argv)
    require_folds_complete(cutoff)
    rows = evaluate(cleaned, areas)
    checks = targets(rows)
    flags = selector_flags(rows)
    lookup = generate(cleaned, areas, reports_up_to, cutoff, path.name, flags)
    try:
        write_lookup(lookup)
    except ValueError as e:  # a short message on the command line instead of a traceback
        sys.exit(str(e))
    RESULTS.write_text(markdown(rows, checks, lookup, reports_up_to, cutoff, path.name), encoding="utf-8")
    for f, t, v, ok in checks:
        print(f"{'pass' if ok else 'MISS'}  {f}  {t}: {v}")
    for s, result in flags.items():
        print(f"{s}: {result['pattern']} ({result['reason']})")
    print(f"Wrote {LOOKUP} and {RESULTS}")


if __name__ == "__main__":
    main()
