"""Baselines and the two-fold rolling backtest (issue #37, roadmap M3).

Run from the repo root: uv run python -m lockout.cli.backtest [path to the police CSV]
Prints the results and writes docs/backtest-results.md.
"""
import sys

from lockout.cli.common import load_cleaned, require_folds_complete
from lockout.models.backtest import EMPTY_AREA_COUNT, HISTORY_MONTHS, backtest
from lockout.paths import DOCS_DIR

OUT = DOCS_DIR / "backtest-results.md"


def markdown(table, reports_up_to, cutoff, source):
    header = "| " + " | ".join(table.columns) + " |\n| " + " | ".join("---" for _ in table.columns) + " |\n"
    body = "".join("| " + " | ".join(str(v) for v in row) + " |\n" for row in table.itertuples(index=False))
    return f"""# Backtest Results: Baselines

Generated by `uv run python -m lockout.cli.backtest data/raw/{source}` from `{source}` (not in Git), with reports up to {reports_up_to:%d %b %Y}. Re-running it on the same file gives the same numbers. With the 14-day lag cutoff, this file counts thefts that ended up to {cutoff:%d %b %Y}, which covers both folds. Reports keep arriving after the cutoff, so a newer file can shift the numbers slightly; compare models on the same file.

## Method

- Two test periods (folds): 1 Apr to 30 Jun 2026 and 1 Jul to 29 Sep 2026.
- Each baseline learns from the {HISTORY_MONTHS} months before its fold and scales that count to the fold's length.
- Citywide share: the same expected count for every area (the city average). It ranks nothing, so its Spearman correlation is n/a.
- Raw area history: each area's own count. An area with no thefts in the history counts as {EMPTY_AREA_COUNT}, because the deviance needs a prediction above 0.
- A theft belongs to the period in which its window ended, as in the cleaning pipeline.
- Lower mean Poisson deviance is better; a Spearman correlation closer to 1 means the areas are ranked more like the actual counts.

## Results

{header}{body}"""


def main():
    path, cleaned, areas, reports_up_to, cutoff = load_cleaned(sys.argv)
    require_folds_complete(cutoff)
    table = backtest(cleaned, areas)
    print(table.to_string(index=False))
    OUT.write_text(markdown(table, reports_up_to, cutoff, path.name), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
