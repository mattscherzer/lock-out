"""Print the baseline backtest and write docs/backtest-results.md.

Run from the repo root: uv run python -m lockout.cli.backtest [path to the police CSV]
"""

import sys

import pandas as pd

from lockout import config
from lockout.cli.common import MODEL_LABELS, fmt, load_cleaned, require_folds_complete, table
from lockout.models.backtest import EMPTY_AREA_COUNT, FOLDS, HISTORY_MONTHS, backtest
from lockout.paths import DOCS_DIR

OUT = DOCS_DIR / "backtest-results.md"


def display(results: pd.DataFrame) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "Fold": results["fold"],
            "Baseline": results["baseline"].map(MODEL_LABELS),
            "Thefts in fold": results["thefts"],
            "Mean Poisson deviance": results["deviance"].map(lambda v: fmt(v, ".3f")),
            "Spearman": results["spearman"].map(lambda v: fmt(v, ".3f")),
        }
    )


def markdown(shown: pd.DataFrame, reports_up_to: pd.Timestamp, cutoff: pd.Timestamp, source: str) -> str:
    spans = " and ".join(
        f"{pd.Timestamp(s).day} {pd.Timestamp(s):%b} to {pd.Timestamp(e).day} {pd.Timestamp(e):%b %Y}" for s, e in FOLDS
    )
    return f"""# Backtest Results: Baselines

Generated by `uv run python -m lockout.cli.backtest data/raw/{source}` from `{source}` (not in Git), with reports up to {reports_up_to:%d %b %Y}. Re-running it on the same file gives the same numbers. With the {config.LAG_CUTOFF_DAYS}-day lag cutoff, this file counts thefts that ended up to {cutoff:%d %b %Y}, which covers both folds. Reports keep arriving after the cutoff, so a newer file can shift the numbers slightly; compare models on the same file.

## Method

- Two test periods (folds): {spans}.
- Each baseline learns from the {HISTORY_MONTHS} months before its fold and scales that count to the fold's length.
- Citywide share: the same expected count for every area (the city average). It ranks nothing, so its Spearman correlation is n/a.
- Raw area history: each area's own count. An area with no thefts in the history counts as {EMPTY_AREA_COUNT}, because the deviance needs a prediction above 0.
- A theft belongs to the period in which its window ended, as in the cleaning pipeline.
- Lower mean Poisson deviance is better; a Spearman correlation closer to 1 means the areas are ranked more like the actual counts.

## Results

{table(list(shown.columns), shown.itertuples(index=False))}
"""


def main() -> None:
    path, cleaned, areas, reports_up_to, cutoff = load_cleaned(sys.argv)
    require_folds_complete(cutoff)
    shown = display(backtest(cleaned, areas))
    print(shown.to_string(index=False))
    OUT.write_text(markdown(shown, reports_up_to, cutoff, path.name), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
