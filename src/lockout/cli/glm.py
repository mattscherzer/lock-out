"""Compare the OSM-count GLM candidates with EB v0 and write docs/glm-results.md.

Run from the repo root after lockout.cli.osm_features:
    uv run python -m lockout.cli.glm data/raw/fahrraddiebstahl_2026-10-26.csv
"""
import sys

import numpy as np
import pandas as pd

from lockout.cli.common import load_cleaned, require_folds_complete, table
from lockout.geo.osm_features import KINDS
from lockout.models.glm import STABILITY_TOLERANCE, FoldResult, Verdict, compare, verdict
from lockout.paths import DOCS_DIR, OSM_FEATURES

OUT = DOCS_DIR / "glm-results.md"
LABELS = {"bike_parking": "bike parking", "shops": "shops", "food_drink": "food and drink places",
          "transit_stops": "transit stops", "education": "schools, colleges and universities"}


def fmt(v: float, pattern: str) -> str:
    return "n/a" if np.isnan(v) else format(v, pattern)


def markdown(folds: list[FoldResult], result: dict[str, Verdict], features: pd.DataFrame, reports_up_to: pd.Timestamp, cutoff: pd.Timestamp,
             source: str, snapshot: pd.Timestamp) -> str:
    rows = [[f["fold"], name, fmt(s["deviance"], ".3f"), fmt(s["spearman"], ".3f"), fmt(s["high_in_top_quartile"], ".0%")]
            for f in folds for name, s in f["scores"].items()]
    coef = [[f["fold"], *(f"{f['coefficients'][c]:.3f}" for c in folds[0]["coefficients"].index)] for f in folds]
    checks = [[name, check, value, "pass" if ok else "MISS"] for name, r in result.items() for check, value, ok in r["checks"]]
    keep = [name for name, r in result.items() if r["keep"]]
    totals = "; ".join(f"{LABELS[k]}: {int(features[k].sum()):,}" for k in KINDS)
    passes = "passes" if len(keep) == 1 else "pass"
    decision = f"{' and '.join(keep)} {passes} every S1 check; adoption is a separate decision (D-22 in the roadmap's decision log)." if keep else "No candidate passes every check, so S1 is cut (roadmap, S1 row)."
    return f"""# S1 Results: OpenStreetMap Counts in a Poisson GLM

Generated by `uv run python -m lockout.cli.glm data/raw/{source}` from `{source}` (not in Git), with reports up to {reports_up_to:%d %b %Y} and thefts counted up to the 14-day cutoff, {cutoff:%d %b %Y}. The folds, history windows and scores are those of `docs/backtest-results.md`; compare models on the same file.

## Features

OpenStreetMap features inside Berlin, counted per planning area by `src/lockout/cli/osm_features.py` (one Overpass request per kind, cached): {totals}. Each area also has its size in km2 from the planning-area data. The counts table was written on {snapshot:%d %b %Y} (the date of `data/raw/osm/osm_features.csv`) from the Overpass responses cached in `data/raw/osm/cache`; a rerun with a new table shows a new date here. The counts come from the current map and are used for the earlier folds too; a model in use would only have the map of its own time. Only these aggregate counts are used. The per-area table (`data/raw/osm/osm_features.csv`) is not in Git until the ODbL question (risk R4) is answered. Data © OpenStreetMap contributors, ODbL.

## Models

- **EB v0:** the current model (`docs/eb-model-results.md`).
- **GLM on OSM counts:** a Poisson GLM of each area's history count on log(1 + count) per kind and log(size).
- **EB toward the GLM:** EB v0's area step, with each area pulled toward its GLM prediction instead of its Bezirksregion.

## Results

Lower deviance is better; Spearman and the High-tier share in the actual top quartile should be high.

{table(["Fold", "Model", "Mean Poisson deviance", "Spearman", "High in top quartile"], rows)}

### GLM coefficients

On the log scale: a coefficient of 0.5 on a kind means that doubling 1 + its count multiplies the expected thefts by about 2^0.5 = 1.41, with the other inputs fixed. Kinds that rise together, such as shops and food and drink places, share their effect, so read their coefficients together, not one by one.

{table(["Fold", *folds[0]["coefficients"].index], coef)}

## Decision checks

The roadmap keeps S1 only if it improves the hold-out deviance over EB v0 and the rankings are stable across folds. Stable is read here as: the Spearman correlation between a model's rates from the two folds is at most {STABILITY_TOLERANCE} below EB v0's (a working rule, not a roadmap figure).

{table(["Candidate", "Check", "Value", "Result"], checks)}

**{decision}**
"""


def main() -> None:
    if not OSM_FEATURES.exists():
        sys.exit(f"{OSM_FEATURES} is missing; run `python -m lockout.cli.osm_features` first.")
    features = pd.read_csv(OSM_FEATURES, dtype={"plr_id": str}).set_index("plr_id")
    path, cleaned, areas, reports_up_to, cutoff = load_cleaned(sys.argv)
    require_folds_complete(cutoff)
    folds = compare(cleaned, areas, features)
    result = verdict(folds)
    OUT.write_text(markdown(folds, result, features, reports_up_to, cutoff, path.name, pd.Timestamp(OSM_FEATURES.stat().st_mtime, unit="s")), encoding="utf-8")
    for f in folds:
        for name, s in f["scores"].items():
            print(f"{f['fold']}  {name}: deviance {s['deviance']:.3f}, Spearman {fmt(s['spearman'], '.3f')}, High in top quartile {fmt(s['high_in_top_quartile'], '.0%')}")
    for name, r in result.items():
        for check, value, ok in r["checks"]:
            print(f"{'pass' if ok else 'MISS'}  {name}: {check}: {value}")
        print(f"{name}: {'passes every check' if r['keep'] else 'fails a check'}")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
