"""Baselines and the two-fold rolling backtest (issue #37, roadmap M3).

Run from the repo root: uv run python src/models/backtest.py [path to the police CSV]
Prints the results and writes docs/backtest-results.md.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.metrics import mean_poisson_deviance

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config
from audit_checks import check_csv, polygon_ids
from fetch_police_csv import find_raw_csv
from pipeline.clean import clean

OUT = Path(__file__).resolve().parents[2] / "docs" / "backtest-results.md"
FOLDS = [("2026-04-01", "2026-06-30"), ("2026-07-01", "2026-09-29")]
HISTORY_MONTHS = 12
EMPTY_AREA_COUNT = 0.5  # history count for an area with no thefts; the deviance needs a prediction above 0


def counts(df, areas, start, end):
    """Thefts per area whose window ended between start and end, both days included."""
    in_period = df["TATZEIT_ENDE_DATUM"].between(pd.Timestamp(start), pd.Timestamp(end))
    return df[in_period].groupby("LOR").size().reindex(areas, fill_value=0)


def days(start, end):
    return (pd.Timestamp(end) - pd.Timestamp(start)).days + 1


def baselines(history, history_days, test_days):
    scale = test_days / history_days
    city = pd.Series(history.sum() / len(history) * scale, index=history.index)
    area = history.where(history > 0, EMPTY_AREA_COUNT) * scale
    return {"Citywide share": city, "Raw area history": area}


def score(actual, predicted):
    # Spearman is undefined when either side is the same for every area
    rho = spearmanr(predicted, actual).statistic if predicted.nunique() > 1 and actual.nunique() > 1 else float("nan")
    return mean_poisson_deviance(actual, predicted), rho


def fold_periods():
    """(history start, history end, fold start, fold end) for each fold: the one place every model takes its windows from."""
    periods = []
    for start, end in FOLDS:
        start, end = pd.Timestamp(start), pd.Timestamp(end)
        periods.append((start - pd.DateOffset(months=HISTORY_MONTHS), start - pd.Timedelta(days=1), start, end))
    return periods


def backtest(df, areas):
    rows = []
    for history_start, history_end, start, end in fold_periods():
        history = counts(df, areas, history_start, history_end)
        actual = counts(df, areas, start, end)
        predictions = baselines(history, days(history_start, history_end), days(start, end))
        for name, predicted in predictions.items():
            deviance, rho = score(actual, predicted)
            rows.append({
                "Fold": f"{start:%Y-%m-%d} to {end:%Y-%m-%d}",
                "Baseline": name,
                "Thefts in fold": int(actual.sum()),
                "Mean Poisson deviance": f"{deviance:.3f}",
                "Spearman": "n/a" if np.isnan(rho) else f"{rho:.3f}",
            })
    return pd.DataFrame(rows)


def markdown(table, reports_up_to, cutoff, source):
    header = "| " + " | ".join(table.columns) + " |\n| " + " | ".join("---" for _ in table.columns) + " |\n"
    body = "".join("| " + " | ".join(str(v) for v in row) + " |\n" for row in table.itertuples(index=False))
    return f"""# Backtest Results: Baselines

Generated by `uv run python src/models/backtest.py data/raw/{source}` from `{source}` (not in Git), with reports up to {reports_up_to:%d %b %Y}. Re-running it on the same file gives the same numbers. With the 14-day lag cutoff, this file counts thefts that ended up to {cutoff:%d %b %Y}, which covers both folds. Reports keep arriving after the cutoff, so a newer file can shift the numbers slightly; compare models on the same file.

## Method

- Two test periods (folds): 1 Apr to 30 Jun 2026 and 1 Jul to 29 Sep 2026.
- Each baseline learns from the {HISTORY_MONTHS} months before its fold and scales that count to the fold's length.
- Citywide share: the same expected count for every area (the city average). It ranks nothing, so its Spearman correlation is n/a.
- Raw area history: each area's own count. An area with no thefts in the history counts as {EMPTY_AREA_COUNT}, because the deviance needs a prediction above 0.
- A theft belongs to the period in which its window ended, as in the cleaning pipeline.
- Lower mean Poisson deviance is better; a Spearman correlation closer to 1 means the areas are ranked more like the actual counts.

## Results

{header}{body}"""


if __name__ == "__main__":
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else find_raw_csv()
    cleaned = clean(check_csv(path))
    cleaned["LOR"] = cleaned["LOR"].str.zfill(8)
    reports_up_to = cleaned["ANGELEGT_AM"].max()
    cutoff = reports_up_to - pd.Timedelta(days=config.LAG_CUTOFF_DAYS)
    if pd.Timestamp(FOLDS[-1][1]) > cutoff:
        sys.exit(f"The file is only complete up to {cutoff:%d %b %Y}, before the last fold ends; use a newer file.")
    table = backtest(cleaned, sorted(polygon_ids()))
    print(table.to_string(index=False))
    OUT.write_text(markdown(table, reports_up_to, cutoff, path.name), encoding="utf-8")
    print(f"Wrote {OUT}")